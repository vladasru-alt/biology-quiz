phase('Авторство')

const results = await pipeline(
  CLUSTERS,
  (c) => agent(
    `${STYLE}

${GLOSSARY}

${CROSS}

${OLD}

ТВОЁ ЗАДАНИЕ: напиши РОВНО 15 вопросов кластера «${c.name}».
Поле topic — только из этих значений, примерно поровну: ${c.topics.map((t) => '"' + t + '"').join(', ')}.
Квота по типам (точно): ${c.quota}.
Сложность: 3 вопроса difficulty 1, 8 — difficulty 2, 4 — difficulty 3. Уровни: около 5 "understand" и 10 "apply".
Ровно 2 вопроса-разбора заблуждения (misconception: true, twotier, skill "диагностика ошибки"), из них не более одного в рамке «Ученик».

СОДЕРЖАНИЕ КЛАСТЕРА: ${c.content}
НЕ ТВОЯ ТЕРРИТОРИЯ: ${c.notYours}.

Верни questions.`,
    { label: `автор ${c.key}`, phase: 'Авторство', schema: QSCHEMA, effort: 'high' }
  ),
  (authored, c) => {
    if (!authored || !authored.questions) return null
    let i1 = c.offset, i2 = c.offset
    const withT = authored.questions.map((q, i) => {
      const t = {}
      if (q.type === 'single' || q.type === 'twotier') { t.options = T1[i1 % 4]; i1++ }
      if (q.type === 'twotier') { t.reasons = T2[i2 % 4]; i2++ }
      return Object.assign({}, q, { _n: c.key + (i + 1), _lengthTarget: t })
    })
    return agent(
      `${STYLE}

${GLOSSARY}

${CROSS}

Ты придирчивый рецензент-биолог. ИСХОДИ ИЗ ТОГО, ЧТО ОШИБКИ ЕСТЬ. Перед тобой ${withT.length} вопросов главы 9, кластер «${c.name}».

Проверь КАЖДЫЙ вопрос:
1. ФАКТЫ — строго по глоссарию. Ловушки: гликолиз идёт в цитоплазме и без O₂; CO₂ дыхания — из декарбоксилирований, а не из O₂; O₂ в цикле Кребса прямо не участвует; O₂ — конечный акцептор электронов, образуется вода; числа учебника — 38 АТФ, 2 АТФ гликолиза и брожения, НАДН 3 АТФ, ФАДН₂ 2 АТФ; молочнокислое брожение обратимо, спиртовое — нет; при спиртовом брожении выделяется CO₂, при молочнокислом — нет; ДК углеводов 1,0, жиров около 0,7; вдох активный, спокойный выдох пассивный; главный стимул дыхания — CO₂; противоток в жабрах. Неверное — исправь.
2. ЕДИНСТВЕННОСТЬ ВЕРНОГО: среди дистракторов нет второго защитимого ответа; для multi отмечены ровно верные; для match right[i] ↔ left[i]; для order порядок верен.
3. ДУБЛИ с другими главами (список выше) и внутри набора; утечки ответа одного вопроса в вариантах или why другого.
4. СТИЛЬ по правилам 3-12: заглавные буквы вариантов после «?», грамматическая одинаковость зеркальных вариантов, «Верно ли…», без «В опыте», рамка «Ученик» ≤1, misconception только true.
5. ДЛИНА: поле _lengthTarget говорит, каким по длине должен быть ПРАВИЛЬНЫЙ вариант среди options (и среди reasons у twotier): «самый длинный», «самый короткий» или «середина» (ни то, ни другое). Добейся ровно этого содержательной переформулировкой; разброс внутри вопроса ≤5 символов. Посчитай символы.
6. why учит механизму и не повторяет дословно одну фразу в разных вопросах.

Верни changes (что исправил, с _n; фактические ошибки — словом ФАКТ) и questions — ВСЕ ${withT.length} вопросов с сохранённым _n, БЕЗ _lengthTarget.

ВОПРОСЫ:
${JSON.stringify(withT, null, 1)}`,
      { label: `рецензент ${c.key}`, phase: 'Проверка', schema: VSCHEMA, effort: 'high' }
    ).then((v) => v ? { key: c.key, targets: withT.map((q) => ({ _n: q._n, t: q._lengthTarget })), changes: v.changes, questions: v.questions } : null)
  }
)

const ok = results.filter(Boolean)

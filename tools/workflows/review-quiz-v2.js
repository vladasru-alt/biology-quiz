function skepticPrompt(t, list) {
  const src = t.kind === 'chapter' ? `Открой инструментом Read файл ${DIR}/${t.ch}.json и проверь каждую находку по самому вопросу (найди его по id).`
    : t.kind === 'cross' ? `Открой нужные главы ${DIR}/chN.json (N — номер главы из id) и проверь каждую находку по обоим вопросам.`
    : `Открой <репозиторий>/index.html (и при необходимости конец <репозиторий>/quiz-data.js со строки 12509) и проследи код по каждому сценарию до конца.`
  return `${PURPOSE}

Ты скептик${t.kind === 'app' ? '-разработчик' : '-биолог'}. Другой рецензент нашёл ${list.length} проблем. Твоя задача — ОПРОВЕРГНУТЬ каждую находку, если она ошибочна, преувеличена или это вкусовщина. ${src}

Для каждой находки (по номеру n) реши:
- "refuted" — проблемы нет (факт верен, второй вариант на деле не защитим, подсказки нет, баг не воспроизводится, пояснение нормальное) или находка — вкусовщина;
- "partly" — проблема есть, но слабее или иная, чем описано;
- "confirmed" — проблема реальна.
Уточни severity по своей оценке. Для confirmed и partly проверь предложенное исправление: оно должно быть верным, ${t.kind === 'app' ? 'не ломать другие сценарии' : 'не создавать второго верного ответа, не выдавать ответ длиной или грамматикой (разброс длины вариантов ≤5, место правильного по длине то же), не дублировать другой вопрос'}. Если исправление плохое — дай своё в поле fix; если хорошее — повтори его. Для refuted поле fix — пустая строка.
${t.kind === 'app' ? '' : 'Факты проверяй строго; при сомнении ищи, не прав ли сам вопрос. Упрощение из учебника — не ошибка, если не вводит в заблуждение.'}

НАХОДКИ:
${JSON.stringify(list.map((f, n) => Object.assign({ n }, f)), null, 1)}`
}

const label = (t) => t.kind === 'chapter' ? t.ch : t.kind === 'cross' ? 'межглавно ' + t.key : 'приложение'

phase('Рецензия')
const results = await pipeline(
  args.tasks,
  (t) => agent(reviewPrompt(t), { label: `рецензент ${label(t)}`, phase: 'Рецензия', schema: t.kind === 'app' ? APP : FINDINGS, effort: 'high' }),
  (rev, t) => {
    if (!rev) return null
    const list = rev.findings || []
    if (!list.length) return { t, rev, verdicts: [] }
    return agent(skepticPrompt(t, list), { label: `скептик ${label(t)}`, phase: 'Перепроверка', schema: VERDICTS, effort: 'high' })
      .then((v) => ({ t, rev, verdicts: v ? v.verdicts : null }))
  }
)

const out = []
for (const r of results.filter(Boolean)) {
  const byN = {}
  ;(r.verdicts || []).forEach((v) => { byN[v.n] = v })
  const findings = (r.rev.findings || []).map((f, n) => {
    const v = byN[n]
    return Object.assign({}, f, { verdict: v ? v.verdict : 'unverified', vSeverity: v ? v.severity : f.severity, vReason: v ? v.reason : '', vFix: v ? v.fix : '' })
  })
  out.push({ task: label(r.t), findings, gaps: r.rev.gaps || [], improvements: r.rev.improvements || [], overall: r.rev.overall })
  const live = findings.filter((f) => f.verdict !== 'refuted')
  log(`${label(r.t)}: находок ${findings.length}, осталось ${live.length} (critical ${live.filter((f) => f.vSeverity === 'critical').length}, major ${live.filter((f) => f.vSeverity === 'major').length})`)
}
const missing = args.tasks.filter((t) => !out.some((o) => o.task === label(t))).map(label)
if (missing.length) log('Не выполнены: ' + missing.join(', '))
return { results: out, missing }
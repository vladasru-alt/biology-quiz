export const meta = {
  name: 'fill-gaps',
  description: 'Новые вопросы на пробелы, найденные повторной проверкой: автор на главу (сначала сверка с банком), затем придирчивая проверка',
  phases: [
    { title: 'Составление', detail: 'автор на главу: какие пробелы реальны, 1-3 вопроса' },
    { title: 'Проверка', detail: 'рецензент проверяет факты, стандарт, утечки и дубли' },
  ],
}

const D = '<рабочая папка>/review3'

const RULES = `Контекст: русскоязычный тренажёр по биологии по учебнику Д. Тейлор, Н. Грин, У. Стаут «Биология», том 1 (главы 1-10, 613 вопросов). Главная задача — помочь научиться: вопрос заставляет вспоминать и рассуждать (retrieval practice), а пояснение why (ученик видит его после любого ответа) учит механизму и снимает типичное заблуждение. Вопросы идут в случайном порядке, варианты перемешиваются; ошибочные возвращаются в интервальном повторении вперемешку с другими главами.

Формат вопроса (JSON): id ("NEW-1", "NEW-2"…), type (single|twotier|multi|truefalse|match|order), level (remember|understand|apply|analyze), steps (1-4), topic (одна из тем главы — список в gaps.json; новую тему заводи, только если пробел — отдельная тема главы учебника), skill (понимание понятия | объяснение механизма | вывод по признакам | предсказание | сравнение | последовательность | диагностика ошибки | воспроизведение факта), difficulty (1-3), misconception (true только у разборов заблуждений, иначе поля нет), q, why; single/twotier — options(4) + correct; twotier — reasonQ, reasons(4), reasonCorrect (второй ярус ОБОСНОВЫВАЕТ ответ первого, а не спрашивает о другом); multi — options(5) + correct (2-3 индекса); truefalse — answer; match — left/right по 3-4 пункта, right[i] соответствует left[i]; order — items (4-5) в верном порядке.

СТАНДАРТ (проверяет линтер):
- проверяет понимание и рассуждение, а не мелочи; один защитимый верный ответ; дистракторы — реальные заблуждения, правдоподобные и грамматически зеркальные; нет «только/лишь/всегда/никогда/вообще/сразу» лишь в неверных;
- разброс длины вариантов ≤5 символов (options, reasons, варианты multi); у single/twotier правильный вариант и правильное обоснование по длине — в СЕРЕДИНЕ (не единственный самый длинный и не единственный самый короткий). ПОСЧИТАЙ длины через Bash (node -e);
- why — 1-2 предложения, учит механизму, разбирает самый привлекательный дистрактор, не начинается с «Верно»/«Неверно»;
- truefalse — «Верно ли…?»; multi — условие кончается на «Отметьте все верные.»; нет «В опыте» в начале условия; после «?» варианты с заглавной; термины банка: глицерол, иод, ЭР, протеазы;
- новый вопрос не дублирует вопрос банка, не раскрывает ответ существующего вопроса своей главы и сам не раскрывается существующими (проверь в обе стороны).`

const QITEM = { type: 'object', properties: { id: { type: 'string' } }, required: ['id'] }

const results = await pipeline(
  args.chapters,
  (ch) => agent(`${RULES}

Твоя глава — ${ch}. Прочитай Read-ом ${D}/gaps.json (раздел ${ch}: название, темы, типы вопросов, число рамок «Ученик…», пробелы от рецензента) и всю главу ${D}/${ch}.json (читай целиком). Сводка всех 613 вопросов банка (условие, ответ, пояснение) — ${D}/all-compact.txt: ищи в ней Grep-ом по ключевым словам каждого пробела.

1. Для каждого пробела реши, реален ли он: если идею уже проверяет вопрос этой или другой главы (назови id), пробел пропусти. Рецензент мог ошибиться — не пиши вопрос ради вопроса.
2. Для реальных пробелов составь новые вопросы: по одному на пробел, всего не больше 3 на главу. Предпочитай типы, которых в главе мало (см. types), если они подходят к идее; рамку «Ученик…» используй, только если в главе её меньше 5 и вопрос действительно разбирает заблуждение.
3. Проверь каждый вопрос по стандарту и посчитай длины.

Верни questions (полные объекты, id "NEW-1"…), skipped (пробел и почему пропущен, с id вопроса, который его уже закрывает) и notes (коротко: какой пробел закрывает каждый вопрос).`,
    { label: `автор ${ch}`, phase: 'Составление', effort: 'high',
      schema: { type: 'object', properties: {
        questions: { type: 'array', items: QITEM },
        skipped: { type: 'array', items: { type: 'object', properties: { gap: { type: 'string' }, reason: { type: 'string' } }, required: ['gap', 'reason'] } },
        notes: { type: 'array', items: { type: 'string' } } }, required: ['questions', 'skipped', 'notes'] } }),
  (au, ch) => {
    if (!au || !(au.questions || []).length) return au ? { ch, au, v: null } : null
    return agent(`${RULES}

Ты придирчивый биолог-рецензент. ИСХОДИ ИЗ ТОГО, ЧТО ОШИБКИ ЕСТЬ. Автор написал ${au.questions.length} новых вопросов для главы ${ch}. Вся глава — ${D}/${ch}.json (прочитай целиком), сводка банка — ${D}/all-compact.txt (Grep).

Проверь каждый вопрос:
1. Факты строго верны и соответствуют уровню учебника; ключ верен; второго защитимого ответа нет; для match/order/multi — соответствия, порядок, отметки.
2. Стандарт: ПОСЧИТАЙ длины (node -e) — разброс ≤5, правильный вариант/обоснование в середине по длине; нет подсказок грамматикой и словами «только/лишь…» в неверных; дистракторы правдоподобны.
3. why 1-2 предложения, учит механизму; для twotier второй ярус обосновывает первый.
4. Нет дубля с вопросами банка и утечек в обе стороны с вопросами главы (найди Grep-ом по ключевым словам).
5. Вопрос учит важной идее главы, а не мелочи.

Исправь всё найденное сам. Если вопрос неисправим (дубль, мелочь) — не включай его и объясни в notes. Верни notes (что поменял, с id; фактические ошибки — словом ФАКТ) и questions — ПОЛНЫЕ итоговые объекты оставленных вопросов.

ЗАМЕТКИ АВТОРА:
${JSON.stringify(au.notes, null, 1)}

ВОПРОСЫ:
${JSON.stringify(au.questions, null, 1)}`,
      { label: `проверка ${ch}`, phase: 'Проверка', effort: 'high',
        schema: { type: 'object', properties: { notes: { type: 'array', items: { type: 'string' } }, questions: { type: 'array', items: QITEM } }, required: ['notes', 'questions'] } }
    ).then((v) => ({ ch, au, v }))
  }
)

const out = {}
for (const r of results.filter(Boolean)) {
  out[r.ch] = { questions: r.v ? r.v.questions : r.au.questions, skipped: r.au.skipped, authorNotes: r.au.notes, reviewNotes: r.v ? r.v.notes : [], verified: !!r.v }
  log(`${r.ch}: новых ${out[r.ch].questions.length}, пропущено пробелов ${r.au.skipped.length}`)
}
const missing = args.chapters.filter((c) => !out[c])
if (missing.length) log('Не выполнены: ' + missing.join(', '))
return { chapters: out, missing }
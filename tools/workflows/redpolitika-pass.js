const S = '<рабочая папка>'
const POLICY = `РЕДПОЛИТИКА, АДАПТИРОВАННАЯ К ТЕСТУ. Исходник — навык редполитики ${'<путь к SKILL.md навыка редполитики>'} (прочитай его целиком, чтобы понимать дух правил). Его отраслевой глоссарий к тесту НЕ относится. Аудитория теста — школьники 15-17 лет углублённого курса биологии и их учителя; тексты: условие вопроса, варианты, обоснования второго яруса, пояснение why (его видят после любого ответа), служебные реплики и надписи интерфейса.

Пять принципов в применении к тесту:
1. ТЕПЛЕЕ. Не додумываем за ученика чувства и мысли («Спокойно», «Не беда», «Не волнуйтесь», «Бывает», «Ничего страшного», «вы наверняка…»). Сочувствие и поддержка — в деле: подсказываем, что сделать дальше. Без казённых и без слишком неформальных формулировок.
2. ПРОЩЕ И ЧЕЛОВЕЧНЕЕ. Без канцелярита: «является», «осуществляет», «данный», «представляет собой», «при наличии», «в ходе», «происходит + отглагольное существительное», «обеспечивает управление», «служит для»… — где есть простая замена. Глагол вместо отглагольного существительного. Разрываем цепочки из трёх и более существительных в родительном падеже. Одно предложение — одна мысль: точку с запятой и длинные многоярусные предложения делим на короткие. Уточнения в скобках встраиваем в предложение или ставим через тире (скобки оставляем для формул, чисел и единиц, например (6C), и для однократного ввода сокращения).
3. НА ОДНОМ ЯЗЫКЕ С АУДИТОРИЕЙ. Научные термины учебника нужны — это предмет изучения, их не заменяем бытовыми словами. Но не больше одного-двух сокращений в предложении: если в одном предложении три и больше (АТФ, НАДФН, ФГК, РуБФ, ТФ…), часть называем словами. Сокращения, которые ученик мог не запомнить (ФГК, РуБФ, ТФ, ДК, БПК, ЧПП и т. п.), расшифровываем при первом упоминании в ЭТОМ вопросе: вопросы идут вразнобой, каждый читается отдельно. Единые термины банка: глицерол, иод, ЭР, протеазы.
4. НА РАВНЫХ. Без снисходительности и заискивания, без оценок сверху вниз («Хорошее решение», «Молодец»); уверенно и прямо: не «попробуйте, возможно…», если можно сказать ясно. Но научные оговорки («обычно», «у большинства») оставляем, если без них утверждение станет неверным. Обращение — на «вы» со строчной. Нейтрально к полу: «Уверен», «Поймал», «Прошёл» — мужской род; ищи формулировки без рода.
5. СО СПОКОЙНОЙ СЕРЬЁЗНОСТЬЮ. Без шуток, мемов, сюсюканья и уменьшительных; геймификация сдержанная.
6. ТИПОГРАФИКА. Неразрывные пробелы после коротких предлогов и в числах приложение будет расставлять само при выводе — в данных их НЕ ставь. Кавычки «ёлочки», тире «—» между словами, дефис в составных словах.`

const STD = `СТАНДАРТ БАНКА, который нельзя нарушить (проверяет линтер):
- смысл, факты и ключ вопроса НЕ меняются; id, type, topic, skill, difficulty, level, steps, misconception не трогать;
- если меняешь options/reasons single/twotier: разброс длины вариантов ≤5 символов и место правильного варианта по длине (самый длинный / самый короткий / середина) — такое же, как было; для multi — разброс ≤5; ПОСЧИТАЙ длины через Bash (node -e). Варианты меняй только при явном нарушении — чаще всего правка нужна в why и в условии;
- why: не длиннее исходного, лучше короче (цель — до ~300 знаков), 1-3 коротких предложения, учит механизму и разбирает привлекательный дистрактор, не начинается с «Верно»/«Неверно»; не добавляй сведений, которые раскрывают ответ другого вопроса главы;
- truefalse — «Верно ли…»; multi — условие кончается на «Отметьте все верные.»; нет «В опыте» в начале условия.`

const QITEM = { type: 'object', properties: { id: { type: 'string' } }, required: ['id'] }
const PATTERNS = { type: 'array', items: { type: 'object', properties: { pattern: { type: 'string' }, count: { type: 'number' }, examples: { type: 'array', items: { type: 'string' } } }, required: ['pattern', 'count', 'examples'] } }

function editPrompt(t) {
  if (t.kind === 'app') return `${POLICY}

Ты редактор интерфейса. Прочитай <репозиторий>/index.html (все строки, которые видит пользователь: надписи кнопок, подсказки HINT и BADGE, CONF, тексты в commit/finish/renderDash/startReview/alert/confirm, placeholder, заголовки, footer) и служебные тексты в конце <репозиторий>/quiz-data.js со строки ~12900 (supportText, streak, microAchievements, focusPrompts, chapterMood, chapterHooks, chapterLabels). Сам банк вопросов не трогай.

Найди нарушения редполитики и предложи замены. Ограничения: смысл и логика интерфейса не меняются (например, если реплика говорит, что вопрос вернётся завтра, так и остаётся); длина надписей кнопок — примерно та же; каждая замена — точная подстрока файла (old), которая встречается в файле ровно один раз, и новый текст (new). Не трогай JS-код, только строковые литералы с текстом для пользователя.

Верни patterns (типичные нарушения: название, сколько раз, 2-3 примера «было → стало») и replacements [{file: "index.html"|"quiz-data.js", old, new, reason}].`
  return `${POLICY}

${STD}

Ты редактор. Твоя глава — ${t.ch}: прочитай целиком ${S}/review3/${t.ch}.json (поля _len/_lenReasons — служебные длины вариантов и место правильного по длине). Механический скан по всему банку лежит в ${S}/red/scan-before.txt — там примеры точек с запятой, скобок, длинных предложений и пояснений, скоплений сокращений.

Пройди КАЖДЫЙ вопрос главы и исправь только настоящие нарушения редполитики (п. 1-5). Хороший вопрос не трогай — правка ради правки вредит. Типичные поводы: точка с запятой и многоярусные предложения в why; пояснение длиннее ~330 знаков; уточнение в скобках; канцелярит и цепочки родительных падежей; три и больше сокращений в предложении или нерасшифрованное редкое сокращение; оценочные или снисходительные слова; корявый порядок слов.

Верни:
- patterns — какие нарушения встретились в главе: название, сколько вопросов, 2-3 примера «было → стало»;
- questions — ПОЛНЫЕ объекты только изменённых вопросов (все поля, без полей с «_», с прежним id);
- changes — id и коротко что сделано.`
}

function checkPrompt(t, ed) {
  if (t.kind === 'app') return `${POLICY}

Ты придирчивый проверяющий. Редактор предложил ${ed.replacements.length} замен в текстах интерфейса (index.html и конец quiz-data.js). Проверь каждую по файлам: old действительно встречается в файле ровно один раз и это текст для пользователя, а не код; смысл и логика сохранены (не обещает того, чего код не делает — проверь по коду рядом); замена лучше по редполитике; нет мужского рода там, где говорится об ученике; надписи кнопок не стали сильно длиннее. Исправь или выброси плохие замены.

Верни notes и replacements — итоговый список [{file, old, new, reason}].

ЗАМЕНЫ:
${JSON.stringify(ed.replacements, null, 1)}`
  return `${POLICY}

${STD}

Ты придирчивый биолог-редактор. ИСХОДИ ИЗ ТОГО, ЧТО ОШИБКИ ЕСТЬ. Редактор изменил ${ed.questions.length} вопросов главы ${t.ch}. Исходные версии и вся глава — ${S}/review3/${t.ch}.json (найди каждый вопрос по id и сравни).

Для каждого вопроса проверь:
1. Смысл и факты не изменились, ни одно верное утверждение не стало неточным при сокращении; ключ прежний; второго защитимого ответа не появилось.
2. Стандарт: посчитай длины (node -e) — разброс ≤5 и место правильного по длине как в _len/_lenReasons исходника; why не длиннее исходного, 1-3 предложения, не начинается с «Верно»/«Неверно»; форматы «Верно ли…», «Отметьте все верные.» на месте.
3. Правка действительно лучше по редполитике: проще, без канцелярита, без точки с запятой, без скоплений сокращений; не появилось новых оценочных слов и мужского рода об ученике.
4. Нет новой утечки ответа в другие вопросы главы.
Если правка хуже исходника или меняет смысл — верни исходную версию вопроса (или исправь сам). Верни notes (что поменял, с id; фактические ошибки — словом ФАКТ) и questions — ПОЛНЫЕ итоговые объекты всех ${ed.questions.length} вопросов.

ИЗМЕНЕНИЯ РЕДАКТОРА:
${JSON.stringify(ed.changes, null, 1)}

ВОПРОСЫ:
${JSON.stringify(ed.questions, null, 1)}`
}

const EDIT_Q = { type: 'object', properties: { patterns: PATTERNS, questions: { type: 'array', items: QITEM }, changes: { type: 'array', items: { type: 'object', properties: { id: { type: 'string' }, what: { type: 'string' } }, required: ['id', 'what'] } } }, required: ['patterns', 'questions', 'changes'] }
const REPL = { type: 'array', items: { type: 'object', properties: { file: { type: 'string' }, old: { type: 'string' }, new: { type: 'string' }, reason: { type: 'string' } }, required: ['file', 'old', 'new', 'reason'] } }
const EDIT_APP = { type: 'object', properties: { patterns: PATTERNS, replacements: REPL }, required: ['patterns', 'replacements'] }
const CHK_Q = { type: 'object', properties: { notes: { type: 'array', items: { type: 'string' } }, questions: { type: 'array', items: QITEM } }, required: ['notes', 'questions'] }
const CHK_APP = { type: 'object', properties: { notes: { type: 'array', items: { type: 'string' } }, replacements: REPL }, required: ['notes', 'replacements'] }

const name = (t) => t.kind === 'app' ? 'интерфейс' : t.ch
const results = await pipeline(
  args.tasks,
  (t) => agent(editPrompt(t), { label: `редактор ${name(t)}`, phase: 'Редактура', effort: 'high', schema: t.kind === 'app' ? EDIT_APP : EDIT_Q }),
  (ed, t) => {
    if (!ed) return null
    const n = t.kind === 'app' ? ed.replacements.length : ed.questions.length
    if (!n) return { t, ed, v: null }
    return agent(checkPrompt(t, ed), { label: `проверка ${name(t)}`, phase: 'Проверка', effort: 'high', schema: t.kind === 'app' ? CHK_APP : CHK_Q }).then((v) => ({ t, ed, v }))
  }
)
const out = {}
for (const r of results.filter(Boolean)) {
  const k = name(r.t)
  out[k] = r.t.kind === 'app'
    ? { patterns: r.ed.patterns, replacements: r.v ? r.v.replacements : r.ed.replacements, notes: r.v ? r.v.notes : [], verified: !!r.v }
    : { patterns: r.ed.patterns, questions: r.v ? r.v.questions : r.ed.questions, changes: r.ed.changes, notes: r.v ? r.v.notes : [], verified: !!r.v }
  log(`${k}: ${r.t.kind === 'app' ? 'замен ' + out[k].replacements.length : 'изменено ' + out[k].questions.length}`)
}
const missing = args.tasks.map(name).filter((k) => !out[k])
if (missing.length) log('Не выполнены: ' + missing.join(', '))
return { results: out, missing }
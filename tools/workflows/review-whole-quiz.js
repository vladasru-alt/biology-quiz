const [app, content] = await Promise.all([appReview, contentResults])

const merged = []
const gaps = []
const overall = []
for (const r of content.filter(Boolean)) {
  const byId = {}
  ;(r.verdicts || []).forEach((v) => { byId[v.id] = byId[v.id] || []; byId[v.id].push(v) })
  const used = {}
  for (const f of r.review.findings || []) {
    const list = byId[f.id] || []
    const k = used[f.id] || 0
    used[f.id] = k + 1
    const v = list[k] || list[0] || null
    merged.push(Object.assign({}, f, { verdict: v ? v.verdict : 'unverified', vSeverity: v ? v.severity : f.severity, vReason: v ? v.reason : '', vFix: v ? v.fix : '' }))
  }
  gaps.push(...(r.review.gaps || []))
  overall.push(...(r.review.overall || []))
}
const count = (s) => merged.filter((m) => m.verdict !== 'refuted' && m.vSeverity === s).length
log(`Находок: ${merged.length}, опровергнуто: ${merged.filter((m) => m.verdict === 'refuted').length}; осталось critical ${count('critical')}, major ${count('major')}, minor ${count('minor')}`)

return { findings: merged, gaps, overall, app }
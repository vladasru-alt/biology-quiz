phase('Правка')

const round = await parallel(UNITS.map((u) => () => agent(
  `${RULES}

Прочитай файл ${SRC} инструментом Read — это JSON с полем questions (60 вопросов с полем _n). Твои — с _n на букву ${u.key}. Остальные — для сведения, чтобы не дублировать и не раскрывать их ответы.

ТОЧНЫЕ ПРАВКИ:
${u.edits}

Больше ничего не меняй. Верни:
- changed: список изменённых вопросов; scope "why", если правилось только пояснение или условие без вариантов, иначе "content";
- questions: ВСЕ 15 вопросов кластера ${u.key} (изменённые и неизменённые) с сохранённым _n.`,
  { label: `редактор ${u.key}`, phase: 'Правка', schema: EDIT_SCHEMA, effort: 'high' }
)))

const ok = round.filter(Boolean)
const byKey = {}
ok.forEach((r) => (r.questions || []).forEach((q) => { byKey[q._n] = q }))
const changed = ok.flatMap((r) => r.changed || [])
log(`Правка: вопросов ${Object.keys(byKey).length}, изменено ${changed.length} (содержание: ${changed.filter((c) => c.scope === 'content').length})`)

const T1 = ['середина', 'самый длинный', 'середина', 'самый короткий']
const T2 = ['середина', 'самый длинный', 'середина', 'самый короткий']
const GROUPS = ['A', 'B', 'C', 'D']

phase('Проверка изменённого')

const verified = await parallel(GROUPS.map((g, gi) => () => {
  const mine = changed.filter((c) => c._n[0] === g && byKey[c._n])
  if (!mine.length) return Promise.resolve({ group: g, changes: [], questions: [], targets: [] })
  let i1 = gi, i2 = gi
  const payload = mine.map((c) => {
    const q = byKey[c._n], t = {}
    if (c.scope === 'content') {
      if (q.type === 'single' || q.type === 'twotier') { t.options = T1[i1 % 4]; i1++ }
      if (q.type === 'twotier') { t.reasons = T2[i2 % 4]; i2++ }
    }
    return Object.assign({}, q, { _edit: c.what, _lengthTarget: t })
  })
  const others = Object.values(byKey).filter((q) => !mine.some((c) => c._n === q._n)).map((q) => ({ _n: q._n, q: q.q }))
  return agent(
    `${RULES}

Ты придирчивый рецензент-биолог. ИСХОДИ ИЗ ТОГО, ЧТО ОШИБКИ ЕСТЬ. Ниже ${payload.length} вопросов главы 9, которые только что правил редактор (поле _edit — что он менял).

Проверь:
1. ФАКТЫ. Ловушки: при блоке цитохромоксидазы переносчики выше блока остаются восстановленными; НАДН гликолиза при наличии O₂ даёт АТФ через дыхательную цепь; зрелые эритроциты человека без митохондрий получают АТФ только гликолизом с образованием лактата; вдыхаемый воздух около 21% O₂ и 0,04% CO₂, выдыхаемый около 16% и 4%; в опыте с термосом контрольные семена кипятят и обеззараживают; жаберная крышка участвует в прокачке воды; свечение светлячка тратит АТФ.
2. Единственность верного ответа; для match right[i] ↔ left[i]; для multi ровно верные отмечены.
3. Правка не создала новых дублей и не раскрывает ответы других вопросов главы (список ниже) и других глав.
4. ДЛИНА: если _lengthTarget не пуст — правильный вариант среди options (и среди reasons у twotier) должен быть ровно «самый длинный», «самый короткий» или «середина» (ни то, ни другое); добейся содержательной переформулировкой. Если пуст — лишь не допусти разброса больше 5 символов. Посчитай символы.
5. Стиль по правилам выше.

Верни changes (что исправил, с _n; фактические ошибки — словом ФАКТ) и questions — все ${payload.length} вопросов с _n, без полей _edit и _lengthTarget.

ВОПРОСЫ:
${JSON.stringify(payload, null, 1)}

ОСТАЛЬНЫЕ ВОПРОСЫ ГЛАВЫ:
${JSON.stringify(others)}`,
    {
      label: `рецензент ${g}`, phase: 'Проверка изменённого', effort: 'high',
      schema: { type: 'object', properties: { changes: { type: 'array', items: { type: 'string' } }, questions: EDIT_SCHEMA.properties.questions }, required: ['changes', 'questions'] },
    }
  ).then((r) => r ? Object.assign({ group: g, targets: payload.map((p) => ({ _n: p._n, t: p._lengthTarget })) }, r) : null)
}))

const vOk = verified.filter(Boolean)
vOk.forEach((r) => (r.questions || []).forEach((q) => { const c = Object.assign({}, q); delete c._edit; delete c._lengthTarget; byKey[q._n] = c }))
const lost = changed.filter((c) => !vOk.some((r) => (r.questions || []).some((q) => q._n === c._n))).map((c) => c._n)
if (lost.length) log('Рецензент не вернул: ' + lost.join(', '))
log(`Итог: ${Object.keys(byKey).length} вопросов`)

return {
  questions: Object.values(byKey),
  changed: changed,
  targets: vOk.flatMap((r) => r.targets || []),
  verifyChanges: vOk.map((r) => ({ group: r.group, changes: r.changes })),
  lost: lost,
}
